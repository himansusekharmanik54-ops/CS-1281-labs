print("Hello, Shop Floor!")
name = input("Operator name: ")
print(f"Welcome aboard, {name}!")

accept_count = 0
rework_count = 0
scrap_count = 0

for i in range(5):
    diameter = float(input(f"Enter diameter for part {i+1}: "))

    if 25 <= diameter <= 75:
        accept_count += 1
        print("ACCEPT")
    elif 10 <= diameter < 24 or 80 < diameter <= 100:
        rework_count += 1
        print("REWORK")
    else:
        scrap_count += 1
        print("SCRAP")

print(f"Final Report: {accept_count} ACCEPT, {rework_count} REWORK, {scrap_count} SCRAP")

total_parts = int(input("Enter total number of parts: "))
box_size = int(input("Enter box size (parts per box): "))

full_boxes = total_parts // box_size
loose_parts = total_parts % box_size

print(f"Full boxes: {full_boxes}")
print(f"Loose parts: {loose_parts}")

audit_result = (full_boxes * box_size) + loose_parts == total_parts
print(f"Audit check (boxes*size + loose == total): {audit_result}")

accept_count = 0
rework_count = 0
scrap_count = 0

batch_size = int(input("How many parts in today's batch? "))

print("\n--- STARTING INSPECTION ---")

for i in range(batch_size):
    diameter = float(input(f"Enter diameter for part {i+1}: "))

    if 9.9 <= diameter <= 10.1:
        accept_count += 1
        print(" -> ACCEPT")
    elif 9.8 <= diameter < 9.9 or 10.1 < diameter <= 10.2:
        rework_count += 1
        print(" -> REWORK")
    else:
        scrap_count += 1
        print(" -> SCRAP")

box_size = 4
full_boxes = accept_count // box_size
loose_parts = accept_count % box_size

print("\n--- END OF SHIFT SUMMARY ---")
print(f"Quality Check: {accept_count} ACCEPT, {rework_count} REWORK, {scrap_count} SCRAP")
print(f"Shipping:      {full_boxes} full boxes of 4")
print(f"Loose Parts:   {loose_parts} accepted parts left over")

print("calculator")

num1 = float(input("Enter the first number: "))
num2 = float(input("Enter the second number: "))

print(f"\nResults for {num1} and {num2}:")

print(f"Addition (+): {num1 + num2}")

print(f"Subtraction (-): {num1 - num2}")

print(f"Multiplication (*): {num1 * num2}")

if num2 != 0:
    print(f"Division (/): {num1 / num2}")
else:
    print("Division (/): Error! Cannot divide by zero.")

