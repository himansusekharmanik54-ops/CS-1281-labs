def parse_and_certify(data_lines):
    valid_records = []
    rejects = []

    for line in data_lines:
        try:
            parsed_value = float(line)
            valid_records.append(parsed_value)

        except ValueError as e:
            rejects.append((line, f"ValueError: {e}"))
        except TypeError as e:
            rejects.append((line, f"TypeError: {e}"))
    valid_count = len(valid_records)
    guarded_average = sum(valid_records) / valid_count if valid_count > 0 else 0.0
    print("=== SHIFT REPORT ===")
    print(f"Valid Records:   {valid_count}")
    print(f"Guarded Average: {guarded_average:.2f}")

    print("\n=== REJECTS TABLE ===")
    if not rejects:
        print("0 records rejected.")
    else:
        for bad_line, reason in rejects:
            print(f"Failed Line: {repr(bad_line):<12} | Reason: {reason}")

    return valid_records, rejects, guarded_average

