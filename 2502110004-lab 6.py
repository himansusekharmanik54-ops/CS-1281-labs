def inspect(dia):
    """Classify a single part diameter (mm) into a bin label."""
    if 24.95 <= dia <= 25.05:
        return "ACCEPT"
    elif 24.90 <= dia <= 25.10:
        return "REWORK"
    return "SCRAP"


def tally(labels):
    """Count occurrences of each bin label and return a count dictionary."""
    counts = {"ACCEPT": 0, "REWORK": 0, "SCRAP": 0}
    for label in labels:
        counts[label] = counts.get(label, 0) + 1
    return counts


def report(shift, counts):
    """Format a shift summary line from a counts dictionary."""
    total = sum(counts.values())
    return (
        f"[{shift}] Total: {total} | "
        f"ACCEPT: {counts.get('ACCEPT', 0)} | "
        f"REWORK: {counts.get('REWORK', 0)} | "
        f"SCRAP: {counts.get('SCRAP', 0)}"
    )


