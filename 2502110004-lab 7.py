class CNCMachine:
    def __init__(self, machine_id, model, max_rpm):
        self.machine_id = machine_id
        self.model = model
        self.__max_rpm = max_rpm
        self.__parts_made = 0
        self.__busy_until = 0

    def __str__(self):
        return f"[{self.machine_id}] {self.model}"

    def is_free(self, current_time):
        return current_time >= self.__busy_until

    def run_job(self, rpm, parts, duration, current_time):
        if not self.is_free(current_time):
            return False
        if rpm <= 0 or rpm > self.__max_rpm or parts <= 0:
            return False
        self.__parts_made += parts
        self.__busy_until = current_time + duration
        return True

    def status(self):
        return {
            "id": self.machine_id,
            "model": self.model,
            "max_rpm": self.__max_rpm,
            "parts_made": self.__parts_made,
            "busy_until": self.__busy_until
        }