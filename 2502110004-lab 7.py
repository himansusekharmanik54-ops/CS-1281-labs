import random


class CNCMachine:
    def __init__(self, machine_id, model, max_rpm):
        self.machine_id = machine_id
        self.model = model
        self.__max_rpm = max_rpm
        self.__parts_made = 0
        self.__jobs_completed = 0
        self.__jobs_rejected = 0

    def __str__(self):
        return f"[{self.machine_id}] {self.model} (Max: {self.__max_rpm} RPM)"

    def run_job(self, rpm, parts):
        if rpm <= 0 or rpm > self.__max_rpm or parts <= 0:
            self.__jobs_rejected += 1
            return False
        self.__parts_made += parts
        self.__jobs_completed += 1
        return True

    def status(self):
        return {
            "id": self.machine_id,
            "model": self.model,
            "max_rpm": self.__max_rpm,
            "parts_made": self.__parts_made,
            "completed": self.__jobs_completed,
            "rejected": self.__jobs_rejected
        }


machine = CNCMachine("M-01", "Haas VF-2", 8000)

for _ in range(10):
    job_rpm = random.randint(3000, 9500)
    job_parts = random.randint(5, 25)
    machine.run_job(job_rpm, job_parts)

report = machine.status()
print(f"SHIFT REPORT - {report['id']} ({report['model']})")
print(f"Jobs Completed : {report['completed']}")
print(f"Jobs Rejected  : {report['rejected']}")
print(f"Total Parts    : {report['parts_made']}")

